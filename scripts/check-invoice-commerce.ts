import ddcnorth from "../shared/brandKits/ddcnorth.json";
import { importInvoiceBrand, cleanInvoiceBrand } from "../shared/invoiceBranding";
import assert from "node:assert/strict";
import { MemoryDb } from "../shared/portable/memoryDb";
import { makeCapabilities } from "../shared/portable/capabilities";
import { tables, society } from "../src/lib/staticConvexFixtures";
import * as inv from "../shared/functions/invoices";
import { DEFAULT_INVOICE_TEMPLATE, catalogRate, invoiceCurrency } from "../shared/invoiceCommerce";
import { invoiceCurrencySummary } from "../shared/invoicing";

const seed: Record<string, any[]> = JSON.parse(JSON.stringify(tables));
seed.users = seed.users.map((u) => ({ ...u, status: "Active", authIssuer: "https://issuer.test", authSubject: `sub-${u._id}` }));
seed.societies = [JSON.parse(JSON.stringify(society)), { _id: "foreign_society", name: "Elsewhere" }];
seed.invoiceCatalogItems.push({ _id: "foreign_item", societyId: "foreign_society", name: "Foreign", unitPriceCents: 100, active: true });
const db = new MemoryDb({ seed });
const societyId = seed.users[0].societyId;
const ctx: any = { db, principal: { kind: "user", runtime: "test", assurance: "trusted-workspace", subject: `sub-${seed.users[0]._id}`, issuer: "https://issuer.test", userId: seed.users[0]._id, societyId }, capabilities: makeCapabilities({}) };
const today = (await inv.workspacePortable(ctx, { societyId })).today;
assert.equal(invoiceCurrency(" usd "), "USD");
assert.throws(() => invoiceCurrency("invalid"), /currency/);
const itemId = await inv.upsertCatalogItemPortable(ctx, { societyId, name: "Labour", kind: "service", sku: "LAB", unit: "hour", currency: "CAD", unitPriceCents: 8500 });
const item = (await db.get(itemId))!;
assert.equal(item.unit, "hour"); assert.equal(item.kind, "service");
const priceListId = await inv.upsertPriceListPortable(ctx, { societyId, name: "Trade", currency: "USD", entries: [{ catalogItemId: itemId, unitPriceCents: 6000 }] });
const list: any = await db.get(priceListId);
assert.equal(catalogRate(item as any, "USD", list), 6000);
assert.equal(catalogRate(item as any, "EUR", list), null, "never silently convert a rate");
assert.equal(catalogRate(item as any, "CAD"), 8500);
assert.equal(catalogRate(item as any, "USD", { ...list, entries: [{ catalogItemId: itemId, unitPriceCents: 0 }] }), 0);
await assert.rejects(() => inv.upsertPriceListPortable(ctx, { societyId, name: "Bad", currency: "CAD", entries: [{ catalogItemId: "foreign_item", unitPriceCents: 1 }] }));
await assert.rejects(() => inv.upsertPriceListPortable(ctx, { societyId, name: "Bad", currency: "CAD", entries: [{ catalogItemId: itemId, unitPriceCents: -1 }] }), /non-negative/);
const brand = importInvoiceBrand(ddcnorth, "https://projects.ahmadjalil.com/brandkit/?brand=ddcnorth");
assert.equal(brand.primary, "#0B2B4A"); assert.equal(brand.font, "inter");
assert.equal((brand.logoSvg.match(/<circle /g) ?? []).length, 6);
assert.throws(() => cleanInvoiceBrand({ ...brand, logoSvg: '<svg><script>alert(1)</script></svg>' }), /vector/);
assert.throws(() => cleanInvoiceBrand({ ...brand, logoSvg: '<svg onload="alert(1)"></svg>' }), /vector/);
const config = { ...DEFAULT_INVOICE_TEMPLATE, brand, name: "Workshop", layout: "modern" as const, accentColor: "#245c46", footer: "Thank you" };
const templateId = await inv.upsertTemplatePortable(ctx, { societyId, config, makeDefault: true });
const repairArgs = { societyId, partyKind: "custom", billToName: "Repair customer", billToEmail: "repair@example.test", receivedDate: today, currency: "CAD", asset: "Bicycle", serialNumber: "FRAME-001", problem: "Brake adjustment", lines: [{ key: "labour", catalogItemId: itemId, item: "Labour", quantity: 1.5, unit: "hour", unitPriceCents: 8500, taxRatePercent: 5, taxLabel: "GST" }] };
const repairId = await inv.upsertRepairJobPortable(ctx, repairArgs);
await inv.setRepairStatusPortable(ctx, { id: repairId, status: "diagnosing" });
await assert.rejects(() => inv.setRepairStatusPortable(ctx, { id: repairId, status: "completed" }), /transition/);
await assert.rejects(() => inv.removeCatalogItemPortable(ctx, { id: itemId }), /in use/);
const invoiceId = await inv.invoiceRepairJobPortable(ctx, { id: repairId });
assert.equal(await inv.invoiceRepairJobPortable(ctx, { id: repairId }), invoiceId, "retry returns the same invoice");
await assert.rejects(() => inv.setRepairStatusPortable(ctx, { id: repairId, status: "cancelled" }), /Void/);
const invoice: any = await db.get(invoiceId);
assert.equal(invoice.repairJobId, repairId); assert.equal(invoice.lines[0].unit, "hour");
assert.equal(invoice.totalCents, 13388); assert.deepEqual(invoice.documentTemplate, config);
await inv.upsertTemplatePortable(ctx, { societyId, id: templateId, config: { ...config, title: "Changed" } });
assert.equal((await db.get(invoiceId))!.documentTemplate.title, "Invoice", "a template edit does not change old invoices");
await inv.upsertRepairJobPortable(ctx, { ...repairArgs, id: repairId, notes: "Ready after test ride" });
await assert.rejects(() => inv.upsertRepairJobPortable(ctx, { ...repairArgs, id: repairId, lines: [] }), /invoiced/);
await assert.rejects(() => inv.upsertPortable(ctx, { ...repairArgs, issueDate: today, terms: "net_30", repairJobId: repairId }), /already has an invoice/);
await assert.rejects(() => inv.upsertPortable(ctx, { ...repairArgs, id: invoiceId, issueDate: today, terms: "net_30", currency: "USD" }), /repair customer and currency/);
const duplicate: any = await db.get(await inv.duplicatePortable(ctx, { id: invoiceId }));
assert.equal(duplicate.repairJobId, undefined); assert.equal(duplicate.documentTemplate.name, "Workshop");
const usdInvoiceId = await inv.upsertPortable(ctx, { ...repairArgs, currency: "USD", priceListId, issueDate: today, terms: "net_30" });
const bankId = await db.insert("financialAccounts", { societyId, name: "Workshop bank", accountType: "Bank", currency: "CAD" });
const txnId = await db.insert("financialTransactions", { societyId, accountId: bankId, date: today, amountCents: 5000, description: "Repair deposit" });
await assert.rejects(() => inv.recordPaymentPortable(ctx, { id: usdInvoiceId, date: today, amountCents: 5000, method: "card", financialTransactionId: txnId }), /currency/);
await assert.rejects(() => inv.recordPaymentPortable(ctx, { id: usdInvoiceId, date: today, amountCents: 5000, method: "card", depositAccountId: bankId }), /currency/);
await inv.recordPaymentPortable(ctx, { id: invoiceId, date: today, amountCents: 5000, method: "e_transfer", financialTransactionId: txnId, reference: "ET-001" });
const ws: any = await inv.workspacePortable(ctx, { societyId });
const repair = ws.repairJobs.find((job: any) => job._id === repairId);
assert.equal(repair.invoice._id, invoiceId); assert.equal(repair.invoice.status, "partially_paid");
assert.equal(repair.invoice.payments[0].method, "e_transfer");
assert.equal(repair.invoice.payments[0].financialTransactionId, txnId);
assert.equal(ws.transactions.find((txn: any) => txn._id === txnId).accountLabel, "Workshop bank");
assert.equal(ws.transactions.find((txn: any) => txn._id === txnId).linkedInvoiceId, invoiceId);
assert.ok(!ws.catalog.some((row: any) => row._id === "foreign_item"));
assert.equal(invoiceCurrencySummary(ws.invoices, "USD", today).draftCents, 13388, "currency totals exclude CAD");
// A replacement repair invoice prevents restoring an older void invoice.
const secondRepair = await inv.upsertRepairJobPortable(ctx, { ...repairArgs, asset: "Second bicycle" });
const oldInvoice = await inv.invoiceRepairJobPortable(ctx, { id: secondRepair });
await inv.voidInvoicesPortable(ctx, { societyId, ids: [oldInvoice] });
const replacement = await inv.invoiceRepairJobPortable(ctx, { id: secondRepair });
assert.notEqual(replacement, oldInvoice);
await assert.rejects(() => inv.restoreVoidedPortable(ctx, { id: oldInvoice }), /active invoice/);
console.log("Invoice commerce checks passed: templates, price lists, repair lifecycle, idempotent billing, payment trace, currency isolation and workspace ownership.");
