import { defineTable } from "convex/server";
import { v } from "convex/values";

const evidenceFields = {
  societyId: v.id("societies"),
  documentId: v.optional(v.id("documents")),
  sourcePage: v.optional(v.number()),
  recordedAt: v.string(),
  recordedBy: v.id("users"),
};

export const businessEvidenceTables = {
  shareNotices: defineTable({
    ...evidenceFields,
    previousId: v.optional(v.id("shareNotices")),
    particulars: v.optional(v.object({
      company: v.optional(v.string()), holder: v.optional(v.string()), shareClass: v.optional(v.string()),
      quantity: v.optional(v.number()), issueOrTransferDate: v.optional(v.string()),
      parValueCents: v.optional(v.number()), transactionType: v.optional(v.string()),
    })),
    transactionId: v.id("rightsholdingTransfers"),
    noticeNumber: v.string(),
    noticeDate: v.string(),
    sentOn: v.optional(v.string()),
    deliveryMethod: v.optional(v.union(v.literal("Email"), v.literal("Mail"), v.literal("Hand delivery"), v.literal("Other"))),
    signer: v.optional(v.string()),
    restrictionLegend: v.optional(v.string()),
    series: v.optional(v.string()),
    resolutionId: v.optional(v.id("writtenResolutions")),
  }).index("by_society", ["societyId"]).index("by_previous", ["previousId"]).index("by_notice", ["societyId", "noticeNumber"]),
  directorConsents: defineTable({
    ...evidenceFields,
    previousId: v.optional(v.id("directorConsents")),
    directorId: v.id("directors"),
    scope: v.union(v.literal("Consent to act"), v.literal("Remote participation"), v.literal("Qualification acknowledgment")),
    event: v.union(v.literal("Given"), v.literal("Withdrawn"), v.literal("Corrected")),
    effectiveDate: v.string(),
    basis: v.optional(v.union(v.literal("Written consent"), v.literal("Meeting record"), v.literal("Conduct"), v.literal("Other"))),
    signedOn: v.optional(v.string()),
    receivedOn: v.optional(v.string()),
    documentDate: v.optional(v.string()),
    reviewStatus: v.optional(v.union(v.literal("Awaiting review"), v.literal("Reviewed"), v.literal("Disputed"))),
    // Meeting basis: the meeting at which the director was elected or appointed.
    meetingId: v.optional(v.id("meetings")),
    // Evidence held elsewhere (paper minute book, counsel's records, another system).
    evidenceLocation: v.optional(v.string()),
    evidenceReference: v.optional(v.string()),
    custodian: v.optional(v.string()),
    // The accountable review, stamped by the server when an entry is saved as
    // Reviewed or Disputed (shared/functions/businessEvidence.ts).
    reviewedBy: v.optional(v.id("users")),
    reviewedByName: v.optional(v.string()),
    reviewedAt: v.optional(v.string()),
    reviewNote: v.optional(v.string()),
  }).index("by_society", ["societyId"]).index("by_previous", ["previousId"]),
  businessChannels: defineTable({
    ...evidenceFields,
    previousId: v.optional(v.id("businessChannels")),
    channel: v.union(v.literal("Phone"), v.literal("Voicemail"), v.literal("Email"), v.literal("Website")),
    value: v.string(),
    purpose: v.string(),
    visibility: v.optional(v.union(v.literal("Internal"), v.literal("Public"), v.literal("Provider only"))),
    custodian: v.optional(v.string()),
    provider: v.optional(v.string()),
    validFrom: v.optional(v.string()),
    validTo: v.optional(v.string()),
    brand: v.optional(v.string()),
    primary: v.optional(v.union(v.literal("Yes"), v.literal("No"))),
    verifiedOn: v.optional(v.string()),
  }).index("by_society", ["societyId"]).index("by_previous", ["previousId"]),
  mailboxServices: defineTable({
    ...evidenceFields,
    previousId: v.optional(v.id("mailboxServices")),
    addressId: v.id("organizationAddresses"),
    agreementId: v.optional(v.id("agreements")),
    boxNumber: v.string(),
    station: v.optional(v.string()),
    size: v.optional(v.string()),
    renter: v.optional(v.string()),
    pickup: v.optional(v.string()),
    custodian: v.optional(v.string()),
    deposit: v.optional(v.union(v.literal("Paid"), v.literal("Required"), v.literal("None"), v.literal("Unknown"))),
    renewalDate: v.optional(v.string()),
    rentalType: v.optional(v.string()),
    deliveryMode: v.optional(v.string()),
    depositAmount: v.optional(v.number()),
    currency: v.optional(v.string()),
  }).index("by_society", ["societyId"]).index("by_previous", ["previousId"]),
  bankRelationships: defineTable({
    ...evidenceFields,
    previousId: v.optional(v.id("bankRelationships")),
    institution: v.string(),
    accountId: v.optional(v.id("financialAccounts")),
    manager: v.optional(v.string()),
    branch: v.optional(v.string()),
    since: v.optional(v.string()),
    contact: v.optional(v.string()),
    language: v.optional(v.string()),
    asOf: v.optional(v.string()),
  }).index("by_society", ["societyId"]).index("by_previous", ["previousId"]),
  clientCardAccess: defineTable({
    ...evidenceFields,
    previousId: v.optional(v.id("clientCardAccess")),
    institution: v.string(),
    lastFour: v.string(),
    cardId: v.optional(v.id("corporateCards")),
    accountId: v.optional(v.id("financialAccounts")),
    cardType: v.union(v.literal("Client access"), v.literal("Debit"), v.literal("Deposit only"), v.literal("Credit")),
    holder: v.optional(v.string()),
    issueNumber: v.optional(v.string()),
    accessRole: v.optional(v.string()),
    cashLimit: v.optional(v.number()),
    instantLimit: v.optional(v.number()),
    purchaseLimit: v.optional(v.number()),
    paymentLimit: v.optional(v.number()),
    currency: v.optional(v.string()),
    limitGroup: v.optional(v.string()),
    asOf: v.optional(v.string()),
    cardStatus: v.optional(v.union(v.literal("Active"), v.literal("Replaced"), v.literal("Closed"), v.literal("Unknown"))),
  }).index("by_society", ["societyId"]).index("by_previous", ["previousId"]),
  governanceDecisions: defineTable({
    ...evidenceFields,
    previousId: v.optional(v.id("governanceDecisions")),
    resolutionId: v.id("writtenResolutions"),
    scope: v.union(v.literal("Borrowing"), v.literal("Guarantees"), v.literal("Security"), v.literal("Banking"), v.literal("Document signing"), v.literal("Auditor waiver"), v.literal("Corporate seal"), v.literal("Other")),
    authority: v.optional(v.string()),
    minimumSigners: v.optional(v.number()),
    exclusions: v.optional(v.string()),
    sealStatus: v.optional(v.union(v.literal("Adopted"), v.literal("Not adopted"), v.literal("Unknown"))),
    effectiveDate: v.optional(v.string()),
    periodStart: v.optional(v.string()),
    periodEnd: v.optional(v.string()),
    consentReview: v.optional(v.union(v.literal("Awaiting review"), v.literal("Reviewed"), v.literal("Incomplete"))),
  }).index("by_society", ["societyId"]).index("by_previous", ["previousId"]),
  identifierDetails: defineTable({
    ...evidenceFields,
    previousId: v.optional(v.id("identifierDetails")),
    identifierId: v.id("organizationIdentifiers"),
    authority: v.optional(v.string()),
    programCode: v.optional(v.string()),
    addressId: v.optional(v.id("organizationAddresses")),
    accountLabel: v.optional(v.string()),
    language: v.optional(v.string()),
    notificationContact: v.optional(v.string()),
    confirmedOn: v.optional(v.string()),
    effectiveTo: v.optional(v.string()),
  }).index("by_society", ["societyId"]).index("by_previous", ["previousId"]),
  recognitionDetails: defineTable({
    ...evidenceFields,
    previousId: v.optional(v.id("recognitionDetails")),
    registrationId: v.id("organizationRegistrations"),
    recognizedAt: v.string(),
    timeZone: v.string(),
    acceptedAt: v.optional(v.string()),
    completingParty: v.optional(v.string()),
    statementDate: v.optional(v.string()),
  }).index("by_society", ["societyId"]).index("by_previous", ["previousId"]),
  equitySubscriptions: defineTable({
    ...evidenceFields,
    previousId: v.optional(v.id("equitySubscriptions")),
    classId: v.id("rightsClasses"),
    subscriber: v.string(),
    quantity: v.number(),
    aggregatePrice: v.optional(v.number()),
    currency: v.optional(v.string()),
    subscribedOn: v.string(),
    acceptedOn: v.optional(v.string()),
    payment: v.optional(v.union(v.literal("Unknown"), v.literal("Outstanding"), v.literal("Partially paid"), v.literal("Paid"))),
    conditions: v.optional(v.string()),
    cancelledOn: v.optional(v.string()),
    transactionId: v.optional(v.id("rightsholdingTransfers")),
  }).index("by_society", ["societyId"]).index("by_previous", ["previousId"]),
};
