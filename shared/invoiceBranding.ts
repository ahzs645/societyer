import svgpath from "svgpath";
import { evenOddPathToNonzero } from "./svgFillRule";
import { BRANDKIT_PROFILE_SCHEMA, brandkitViewBox, normalizeBrandkitLogo } from "./brandkitLogo";
/** Data-only presentation snapshots: importing a brand never changes organization details. */
export type InvoiceBrand = {
  id: string; name: string; version: string; sourceUrl?: string;
  primary: string; ink: string; paper: string; muted: string; light: string;
  font: "inter" | "serif" | "sans";
  logoSvg: string; logoWidth: number; logoHeight: number;
  descriptor?: string;
  consumerProfileSchema?: typeof BRANDKIT_PROFILE_SCHEMA;
  logoVariants?: { black: string; reverse: string };
  sourceTypography?: { body: string; heading: string; label: string };
  provenance?: { source?: string; status?: string };
};
const hex = (value: unknown, fallback: string) => /^#[0-9a-f]{6}$/i.test(String(value)) ? String(value) : fallback;
const xml = (value: string) => value.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;" })[c]!);
const number = (value: unknown, fallback: number, max = 10000) => Number.isFinite(Number(value)) && Number(value) >= 0 && Number(value) <= max ? Number(value) : fallback;

export function cleanInvoiceBrand(raw: InvoiceBrand): InvoiceBrand {
  if (!raw || typeof raw !== "object" || typeof raw.name !== "string" || !raw.name.trim()) throw new Error("The brand needs a name.");
  const svg = String(raw.logoSvg ?? "");
  const portable = raw.consumerProfileSchema === BRANDKIT_PROFILE_SCHEMA;
  let portableFields: Partial<InvoiceBrand> = {};
  if (portable) {
    const viewBox = brandkitViewBox([0, 0, raw.logoWidth, raw.logoHeight]);
    if (!raw.logoVariants) throw new Error("The Brandkit profile needs primary, black and reverse logos.");
    const family = (value: unknown) => typeof value === "string" ? value.trim().slice(0, 120) : "";
    const provenance = (value: unknown) => typeof value === "string" ? value.trim().slice(0, 2000) || undefined : undefined;
    portableFields = { consumerProfileSchema: BRANDKIT_PROFILE_SCHEMA, logoWidth: viewBox[2], logoHeight: viewBox[3],
      logoSvg: normalizeBrandkitLogo(svg, viewBox), logoVariants: { black: normalizeBrandkitLogo(raw.logoVariants.black, viewBox), reverse: normalizeBrandkitLogo(raw.logoVariants.reverse, viewBox) },
      ...(raw.sourceTypography ? { sourceTypography: { body: family(raw.sourceTypography.body), heading: family(raw.sourceTypography.heading), label: family(raw.sourceTypography.label) } } : {}),
      ...(raw.provenance ? { provenance: { source: provenance(raw.provenance.source), status: provenance(raw.provenance.status) } } : {}),
    };
  }
  // Only the SVG subset generated by this adapter is accepted. Never accept active SVG or external resources.
  // Existing saved snapshots keep their original geometry and rendering behavior.
  if (!portable && (raw.logoVariants || raw.consumerProfileSchema || svg.length > 100000 || !/^<svg\b/.test(svg) || /<(?!\/?(?:svg|g|path|circle|title)\b)|\bon\w+\s*=|(?:href|url|style|transform)\s*[=(]|<!/i.test(svg))) throw new Error("The brand logo must be a self-contained vector logo.");
  return { id: String(raw.id ?? "custom").slice(0, 80), name: raw.name.trim().slice(0, 100), version: String(raw.version ?? "1").slice(0, 100),
    sourceUrl: typeof raw.sourceUrl === "string" && raw.sourceUrl.startsWith("https://") ? raw.sourceUrl.slice(0, 500) : undefined,
    primary: hex(raw.primary, "#0B2B4A"), ink: hex(raw.ink, "#000000"), paper: hex(raw.paper, "#FFFFFF"), muted: hex(raw.muted, "#4B4F56"), light: hex(raw.light, "#C8D7E8"),
    font: ["inter", "serif", "sans"].includes(raw.font) ? raw.font : "sans", logoSvg: svg,
    logoWidth: Math.max(1, number(raw.logoWidth, 400)), logoHeight: Math.max(1, number(raw.logoHeight, 120)), descriptor: String(raw.descriptor ?? "").slice(0, 200) || undefined,
    ...portableFields,
  };
}

function importConsumerProfile(data: Record<string, any>, sourceUrl?: string): InvoiceBrand {
  if (typeof data.name !== "string" || !data.name.trim()) throw new Error("The Brandkit profile needs a name.");
  const primary = data.logos?.primary;
  const viewBox = brandkitViewBox(primary?.viewBox);
  for (const variant of ["primary", "black", "reverse"]) {
    const box = brandkitViewBox(data.logos?.[variant]?.viewBox);
    if (box.some((n, index) => n !== viewBox[index])) throw new Error("The Brandkit logo variants must share a viewBox.");
  }
  for (const role of ["ink", "paper", "primary", "muted", "light", "reverse", "line", "rule"]) {
    if (!/^#[0-9a-f]{6}$/i.test(data.colours?.[role] ?? "")) throw new Error(`The Brandkit profile needs a resolved ${role} color.`);
  }
  const body = data.typography?.body;
  if (typeof body?.family !== "string" || !body.family.trim()) throw new Error("The Brandkit profile needs its source body font family.");
  // Document fonts stay local. Source font names are metadata, never CSS or remote font URLs.
  const serif = /serif|times|termes|georgia/i.test(body.family.replace(/sans[ -]?serif/gi, "")) || /(?:^|,)\s*serif\s*$/i.test(String(body.fallback ?? ""));
  return cleanInvoiceBrand({ id: data.id, name: data.name, version: data.version, sourceUrl: sourceUrl ?? data.sourceUrl,
    primary: data.colours.primary, ink: data.colours.ink, paper: data.colours.paper, muted: data.colours.muted, light: data.colours.light,
    font: /^inter$/i.test(body.family.trim()) ? "inter" : serif ? "serif" : "sans",
    logoSvg: primary.svg, logoWidth: viewBox[2], logoHeight: viewBox[3], consumerProfileSchema: BRANDKIT_PROFILE_SCHEMA,
    logoVariants: { black: data.logos.black.svg, reverse: data.logos.reverse.svg },
    sourceTypography: { body: body.family, heading: data.typography?.heading?.family, label: data.typography?.label?.family }, provenance: data.provenance,
  });
}

export function importInvoiceBrand(input: unknown, sourceUrl?: string): InvoiceBrand {
  const data = input as Record<string, any>;
  if (!data || typeof data !== "object" || Array.isArray(data)) throw new Error("Choose a Brandkit consumer-profile.json or supported brand.json file.");
  if (data.schema === BRANDKIT_PROFILE_SCHEMA) return importConsumerProfile(data, sourceUrl);
  if (typeof data.schema === "string" && data.schema.startsWith("brandkit/consumer-profile/")) throw new Error("This Brandkit consumer profile version is not supported.");
  if (data.logoSvg) return cleanInvoiceBrand(data as InvoiceBrand);
  if (!data.name || !Array.isArray(data.symbol?.centres) || !data.wordmark?.variants) throw new Error("Export source/consumer-profile.json from the Brandkit download to import this brand. Raw brand.json import supports circle symbols with outlined wordmarks.");
  const colours = data.colours ?? {};
  const colour = (role: string, fallback: string) => hex(colours[data.roles?.[role]] ?? data.roles?.[role], fallback);
  const primary = colour("primary", "#0B2B4A");
  const variant = data.wordmark.variants[data.id] ?? Object.values(data.wordmark.variants)[0] as any;
  if (!Array.isArray(variant?.parts) || variant.parts.length > 30 || data.symbol.centres.length > 100) throw new Error("The brand logo geometry is not supported.");
  const symbolHeight = number(data.symbol.viewBox?.[3], 256);
  if (!symbolHeight) throw new Error("The logo symbol needs a positive height.");
  const iconHeight = number(data.lockup?.iconHeight, 120);
  const typeHeight = number(data.lockup?.wordmarkHeight, 120);
  const wordmarkHeight = number(data.wordmark.height, 82.5);
  if (!wordmarkHeight) throw new Error("The wordmark needs a positive height.");
  const scale = typeHeight / wordmarkHeight;
  const left = iconHeight + number(data.lockup?.iconGap, 12);
  const padding = number(data.lockup?.canvasPadding, 16);
  const width = padding * 2 + left + number(variant.width, 400) * scale;
  const height = padding * 2 + Math.max(iconHeight, typeHeight);
  const circles = data.symbol.centres.map((point: any) => {
    if (!Array.isArray(point) || point.length !== 2 || point.some((n: any) => !Number.isFinite(n) || n < 0 || n > 10000)) throw new Error("Invalid symbol geometry.");
    const symbolScale = iconHeight / symbolHeight;
    return `<circle fill="${primary}" cx="${padding + point[0] * symbolScale}" cy="${padding + point[1] * symbolScale}" r="${number(data.symbol.radius, 40) * symbolScale}"/>`;
  }).join("");
  const paths = variant.parts.map((part: any) => {
    const path = data.wordmark.glyphs?.[part.glyph];
    if (typeof path !== "string" || path.length > 50000 || !/^[MmZzLlHhVvCcSsQqTtAaEe0-9+.,\s-]+$/.test(path)) throw new Error("Invalid outlined wordmark geometry.");
    const flatPath = svgpath(path).translate(number(part.x, 0), 0).scale(scale).translate(left + padding, padding).round(6).toString();
    return `<path fill="${primary}" d="${flatPath}"${part.fillRule === "evenodd" ? ' fill-rule="evenodd"' : ""}/>`;
  }).join("");
  const logoSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}"><title>${xml(String(data.name).slice(0, 100))}</title>${circles}${paths}</svg>`;
  const font = data.typography?.body?.family ?? data.fonts?.body?.family ?? "";
  return cleanInvoiceBrand({ id: String(data.id ?? "custom"), name: String(data.name), version: String(data.version ?? "1"), sourceUrl, primary, ink: colour("ink", "#000000"), paper: colour("paper", "#FFFFFF"), muted: colour("muted", "#4B4F56"), light: colour("light", "#C8D7E8"), font: /inter/i.test(font) ? "inter" : /serif|times/i.test(font) ? "serif" : "sans", logoSvg, logoWidth: width, logoHeight: height, descriptor: data.copy?.descriptor });
}

export function invoiceBrandLogo(brand: InvoiceBrand, variant: "primary" | "black" | "reverse" = "primary") {
  if (brand.consumerProfileSchema === BRANDKIT_PROFILE_SCHEMA && brand.logoVariants) return variant === "primary" ? brand.logoSvg : brand.logoVariants[variant];
  const fill = variant === "black" ? "#000000" : variant === "reverse" ? "#FFFFFF" : brand.primary;
  return brand.logoSvg.replace(/fill="#[0-9a-f]{6}"/gi, `fill="${fill}"`);
}

export function invoiceBrandFontDescription(brand: InvoiceBrand): string {
  const rendered = brand.font === "serif" ? "Noto Serif" : "Inter";
  const requested = brand.sourceTypography?.body;
  return requested && requested.toLowerCase() !== rendered.toLowerCase() ? `${rendered} (fallback for ${requested})` : rendered;
}

/** Forme's vector subset consumes point coordinates; bake the SVG viewport scale into its geometry. */
export function invoiceBrandPdfSvg(brand: InvoiceBrand, variant: "primary" | "black" | "reverse" = "primary", width = 200) {
  const scale = width / brand.logoWidth;
  const portable = brand.consumerProfileSchema === BRANDKIT_PROFILE_SCHEMA;
  return invoiceBrandLogo(brand, variant).replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "")
    .replace(/<path\b[^>]*>/g, (element) => element.replace(/\bd="([^"]+)"/g, (_match, path: string) => {
      const geometry = svgpath(path).scale(scale);
      // Forme's SVG subset does not interpret shorthand smooth curves consistently.
      // Limit this normalization to new profiles so existing document snapshots stay stable.
      if (portable) geometry.abs().unshort().unarc();
      const scaled = geometry.round(6).toString();
      return `d="${/fill-rule="evenodd"/.test(element) ? evenOddPathToNonzero(scaled) : scaled}"`;
    }))
    .replace(portable ? /\b(cx|cy|r|stroke-width)="([0-9.+e-]+)"/gi : /\b(cx|cy|r)="([0-9.+e-]+)"/gi, (_match, attr: string, value: string) => `${attr}="${Number(value) * scale}"`);
}
