import { useState } from "react";
import { useMutation } from "convex/react";
import { Link } from "react-router-dom";
import { api } from "@/lib/convexApi";
import { Badge } from "./ui";
import { DatePicker } from "./DatePicker";
import { useToast } from "./Toast";
import { CORPORATION_REPORT_PACKETS, isRestrictedReportPacketKey } from "../../shared/corporationReportPackets";
import { isCorporation } from "../../shared/organizationDomain";
import { todayDateOnly } from "../../shared/dateOnly";

const RESTRICTED_ROLES = new Set(["Owner", "Admin", "Director"]);

/**
 * Minute-book reports for a corporation: printed registers, a corporate
 * information summary, director consents, a covering letter and (BC) the
 * transparency register and LOTA worksheet, each generated "as of" a date from
 * the registers. Restricted registers can only be generated by a director or a
 * workspace administrator; the server enforces the same rule.
 */
export function MinuteBookReportsCard({
  society,
  allowedPacketKeys,
  canWrite,
  role,
}: {
  society: any;
  allowedPacketKeys: Set<string>;
  canWrite: boolean;
  role: string | null;
}) {
  const generate = useMutation(api.legalOperations.generateDocumentFromCatalog);
  const toast = useToast();
  const [asOf, setAsOf] = useState(todayDateOnly());
  const [busyKey, setBusyKey] = useState<string | null>(null);
  const [doneKey, setDoneKey] = useState<string | null>(null);

  if (!isCorporation(society)) return null;
  const reports = CORPORATION_REPORT_PACKETS.filter((packet) => allowedPacketKeys.has(packet.key));
  if (!reports.length) return null;
  const mayViewRestricted = RESTRICTED_ROLES.has(role ?? "");

  const onGenerate = async (packetKey: string) => {
    if (!asOf) return;
    setBusyKey(packetKey);
    try {
      await generate({ societyId: society._id, packetKey, effectiveDate: asOf });
      setDoneKey(packetKey);
      setTimeout(() => setDoneKey(null), 4000);
    } catch (error: any) {
      toast.error("Could not prepare the report", error?.message ?? String(error));
    } finally {
      setBusyKey(null);
    }
  };

  return (
    <div className="card" style={{ marginBottom: 16 }}>
      <div className="card__head">
        <h2 className="card__title">Minute book reports</h2>
        <Badge>{reports.length}</Badge>
      </div>
      <div className="card__body" style={{ display: "flex", flexDirection: "column", gap: 12 }}>
        <p className="muted" style={{ margin: 0, fontSize: 13 }}>
          Printable outputs built from the registers as they stood on the chosen date. Each one is a working copy to review, not a certified record.
        </p>
        <label style={{ display: "flex", alignItems: "center", gap: 8, fontSize: 13 }}>
          <span>As of</span>
          <DatePicker value={asOf} onChange={(value) => setAsOf(value)} size="sm" />
        </label>
        {reports.map((packet) => {
          const restricted = isRestrictedReportPacketKey(packet.key);
          const blocked = restricted && !mayViewRestricted;
          return (
            <div key={packet.key} style={{ borderTop: "1px solid var(--border)", paddingTop: 10 }}>
              <div style={{ display: "flex", alignItems: "center", gap: 8, flexWrap: "wrap" }}>
                <strong>{packet.templateName}</strong>
                {restricted && <Badge tone="warn">Restricted</Badge>}
                <span style={{ marginLeft: "auto" }}>
                  {doneKey === packet.key ? (
                    <span style={{ color: "var(--green-11)", fontSize: 13 }}>
                      Prepared ✓ — <Link to="/app/template-engine">Open Template Engine</Link>
                    </span>
                  ) : (
                    <button
                      className="btn btn--accent"
                      disabled={!canWrite || blocked || !asOf || busyKey === packet.key}
                      title={!canWrite ? "Document editing permission is required" : blocked ? "Only a director or a workspace administrator can prepare this register" : "Prepare this report as of the chosen date"}
                      onClick={() => onGenerate(packet.key)}
                    >
                      {busyKey === packet.key ? "Preparing…" : "Prepare"}
                    </button>
                  )}
                </span>
              </div>
              <p style={{ margin: "6px 0 0", color: "var(--text-secondary)", fontSize: 13 }}>{packet.summary}</p>
            </div>
          );
        })}
      </div>
    </div>
  );
}
